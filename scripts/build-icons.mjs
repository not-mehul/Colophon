#!/usr/bin/env node
// Inlines the Lucide icons Colophon uses into src/icons.js (style.md §9), so
// nothing the UI needs to draw itself touches the network.
//
//   npm run icons
//
// Reads the pinned lucide-static devDependency. Every data-lucide="name" in
// index.html and src/app.js is picked up; names chosen at runtime go in EXTRA.

import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const require = createRequire(import.meta.url);
const pkgDir = dirname(require.resolve('lucide-static/package.json'));
const version = JSON.parse(readFileSync(join(pkgDir, 'package.json'), 'utf8')).version;

const EXTRA = ['check', 'alert-triangle', 'x-circle', 'eye', 'eye-off', 'file-warning', 'layers', 'list-ordered', 'book'];

const sources = ['index.html', 'src/app.js'].map((f) => readFileSync(join(root, f), 'utf8')).join('\n');
const names = new Set(EXTRA);
for (const m of sources.matchAll(/data-lucide="([a-z0-9-]+)"/g)) names.add(m[1]);

const icons = {};
for (const name of [...names].sort()) {
  const svg = readFileSync(join(pkgDir, 'icons', `${name}.svg`), 'utf8');
  const inner = svg
    .slice(svg.indexOf('>', svg.indexOf('<svg')) + 1, svg.lastIndexOf('</svg>'))
    .replace(/\s*\n\s*/g, '')
    .replace(/\s+\/>/g, '/>');
  icons[name] = inner;
}

const out = `// Generated by scripts/build-icons.mjs from lucide-static ${version} (ISC licence). Do not edit.
// A drop-in for lucide.createIcons(): swaps every <i data-lucide="name"> for an inline SVG.
(function () {
  'use strict';
  var ICONS = ${JSON.stringify(icons, null, 2)};
  var NS = 'http://www.w3.org/2000/svg';

  function swap(el) {
    var name = el.getAttribute('data-lucide');
    var inner = ICONS[name];
    if (inner === undefined) return;
    var svg = document.createElementNS(NS, 'svg');
    svg.setAttribute('xmlns', NS);
    svg.setAttribute('width', '24');
    svg.setAttribute('height', '24');
    svg.setAttribute('viewBox', '0 0 24 24');
    svg.setAttribute('fill', 'none');
    svg.setAttribute('stroke', 'currentColor');
    svg.setAttribute('stroke-width', '2');
    svg.setAttribute('stroke-linecap', 'round');
    svg.setAttribute('stroke-linejoin', 'round');
    for (var i = 0; i < el.attributes.length; i++) {
      var a = el.attributes[i];
      if (a.name !== 'data-lucide') svg.setAttribute(a.name, a.value);
    }
    if (!svg.hasAttribute('aria-label')) svg.setAttribute('aria-hidden', 'true');
    svg.setAttribute('class', ('lucide lucide-' + name + ' ' + (el.getAttribute('class') || '')).trim());
    svg.innerHTML = inner;
    el.replaceWith(svg);
  }

  window.lucide = {
    icons: ICONS,
    createIcons: function (opts) {
      var roots = (opts && opts.nodes) || [document];
      roots.forEach(function (root) {
        if (!root) return;
        if (root.matches && root.matches('[data-lucide]')) swap(root);
        if (root.querySelectorAll) root.querySelectorAll('[data-lucide]').forEach(swap);
      });
    }
  };
})();
`;
writeFileSync(join(root, 'src/icons.js'), out);
console.log(`Wrote src/icons.js: ${names.size} icons from lucide-static ${version}.`);
